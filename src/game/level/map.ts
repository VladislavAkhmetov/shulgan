export function zoneAt(zones: Zone[], x: number, z: number) {
  const c = Math.floor(x / CELL)
  const r = Math.floor(z / CELL)
  return zones.findIndex((zn) => zn.rects.some(([c0, r0, c1, r1]) => c >= c0 && c <= c1 && r >= r0 && r <= r1))
}
