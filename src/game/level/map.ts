export interface Marker {
  ch: string
  col: number
  row: number
  x: number
  z: number
}

export interface LevelData {
  cols: number
  rows: number
  width: number
  depth: number
  /** 1 = walkable floor */
  walk: Uint8Array
  /** 1 = shallow water */
  water: Uint8Array
  /** 1 = deep water under the cell (the black lakes, the underground river, the gap under a drawbridge) */
  deep: Uint8Array
  /** 1 = no way through, but the eye goes over it (deep water): line of sight and arrows pass */
  open: Uint8Array
  markers: Marker[]
}

/** `%` deep water is not floor; everything else that is not a wall is */
export const isFloorChar = (ch: string) => ch !== '#' && ch !== ' ' && ch !== '%'

export function parseLevel(map: string[] = MAP): LevelData {
  const rows = map.length
  const cols = Math.max(...map.map((r) => r.length))
  const walk = new Uint8Array(cols * rows)
  const water = new Uint8Array(cols * rows)
  const deep = new Uint8Array(cols * rows)
  const open = new Uint8Array(cols * rows)
  const markers: Marker[] = []
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const ch = map[r][c] ?? '#'
      const i = r * cols + c
      if (ch === '%') {
        deep[i] = 1
        open[i] = 1
      } else if (isFloorChar(ch)) {
        walk[i] = 1
        if (ch === '~') water[i] = 1
        else if (ch !== '.') {
          // the drawbridge spans deep water: walkable once it is down (a barrier holds it until then)
          if (ch === '_') deep[i] = 1
          markers.push({ ch, col: c, row: r, x: (c + 0.5) * CELL, z: (r + 0.5) * CELL })
        }
      }
    }
  }
  return { cols, rows, width: cols * CELL, depth: rows * CELL, walk, water, deep, open, markers }
}

