export interface Marker {
  ch: string
  col: number
  row: number
  x: number
  z: number
}

export interface LevelData {
  cols: number
  rows: number
  width: number
  depth: number
  /** 1 = walkable floor */
  walk: Uint8Array
  /** 1 = shallow water */
  water: Uint8Array
  markers: Marker[]
}

export const isFloorChar = (ch: string) => ch !== '#' && ch !== ' '

export function parseLevel(map: string[] = MAP): LevelData {
  const rows = map.length
  const cols = Math.max(...map.map((r) => r.length))
  const walk = new Uint8Array(cols * rows)
  const water = new Uint8Array(cols * rows)
  const markers: Marker[] = []
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const ch = map[r][c] ?? '#'
      if (isFloorChar(ch)) {
        walk[r * cols + c] = 1
        if (ch === '~') water[r * cols + c] = 1
        else if (ch !== '.') {
          markers.push({ ch, col: c, row: r, x: (c + 0.5) * CELL, z: (r + 0.5) * CELL })
        }
      }
    }
  }
  return { cols, rows, width: cols * CELL, depth: rows * CELL, walk, water, markers }
}

